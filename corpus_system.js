root.initCorpusEngine = function(config) {
    config = config || {};
    const cardsContainerId = config.cardsContainerId || "corpusCardsContainer";
    const filterBtnsClass = config.filterBtnsClass || "corpus-filter-btn";
    const searchInputId = config.searchInputId || "corpusSearchInput";
    const countBadgeId = config.countBadgeId || "corpusCountBadge";
    const emptyStateId = config.emptyStateId || "corpusEmptyState";

    const container = document.getElementById(cardsContainerId);
    if (!container) return;

    let currentDomain = "all";
    let searchQuery = "";

    const filterBtns = document.querySelectorAll("." + filterBtnsClass);
    const searchInput = document.getElementById(searchInputId);
    const countBadge = document.getElementById(countBadgeId);
    const emptyState = document.getElementById(emptyStateId);

    function updateView() {
        const cards = container.querySelectorAll(".corpus-card");
        let visibleCount = 0;
        const q = searchQuery.toLowerCase().trim();

        cards.forEach(function(card) {
            const cardDomain = card.getAttribute("data-domain");
            const domainMatch = (currentDomain === "all" || cardDomain === currentDomain);
            const textContent = card.textContent.toLowerCase();
            const searchMatch = !q || textContent.includes(q);

            if (domainMatch && searchMatch) {
                card.classList.remove("hidden");
                visibleCount++;
            } else {
                card.classList.add("hidden");
            }
        });

        if (countBadge) {
            if (visibleCount === 49) {
                countBadge.textContent = "49 références";
            } else {
                countBadge.textContent = visibleCount + " référence" + (visibleCount > 1 ? "s" : "") + " affichée" + (visibleCount > 1 ? "s" : "");
            }
        }

        if (emptyState) {
            if (visibleCount === 0) {
                emptyState.classList.remove("hidden");
            } else {
                emptyState.classList.add("hidden");
            }
        }
    }

    filterBtns.forEach(function(btn) {
        btn.addEventListener("click", function() {
            const domain = btn.getAttribute("data-domain");
            currentDomain = domain;

            filterBtns.forEach(function(b) {
                b.classList.remove("bg-indigo-600", "text-white");
                b.classList.add("bg-slate-800", "text-slate-300");
            });
            btn.classList.add("bg-indigo-600", "text-white");
            btn.classList.remove("bg-slate-800", "text-slate-300");

            updateView();
        });
    });

    if (searchInput) {
        searchInput.addEventListener("input", function(e) {
            searchQuery = e.target.value;
            updateView();
        });
    }

    root.resetCorpusSearch = function() {
        if (searchInput) searchInput.value = "";
        searchQuery = "";
        currentDomain = "all";
        filterBtns.forEach(function(b) {
            if (b.getAttribute("data-domain") === "all") {
                b.classList.add("bg-indigo-600", "text-white");
                b.classList.remove("bg-slate-800", "text-slate-300");
            } else {
                b.classList.remove("bg-indigo-600", "text-white");
                b.classList.add("bg-slate-800", "text-slate-300");
            }
        });
        updateView();
    };

    updateView();
};

